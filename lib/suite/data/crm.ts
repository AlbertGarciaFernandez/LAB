export const updateOpportunityStage = (id: string, stage: Opportunity["stage"]) => {
  const opportunity = opportunities.find((o) => o.id === id);
  if (opportunity) {
    opportunity.stage = stage;
    opportunity.lastActivityAt = new Date().toISOString();
  }
  return opportunity;
};

export const toggleTaskStatus = (id: string) => {
  const task = tasks.find((t) => t.id === id);
  if (task) {
    task.status = task.status === "done" ? "todo" : "done";
  }
  return task;
};

export const markEmailRead = (id: string) => {
  const email = emails.find((e) => e.id === id);
  if (email) {
    email.readAt = new Date().toISOString();
  }
  return email;
};

export const addWhatsAppMessage = (chatId: string, content: string) => {
  const chat = whatsAppChats.find((c) => c.id === chatId);
  if (!chat) return undefined;

  const message: WhatsAppMessage = {
    id: `${chatId}_msg_${chat.messages.length + 1}`,
    chatId,
    sender: "user",
    content,
    sentAt: new Date().toISOString(),
    read: true,
  };

  chat.messages.push(message);
  chat.lastMessageAt = message.sentAt;
  return message;
};
